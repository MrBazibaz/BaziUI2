local function has(flags, mask)
    return flags % (mask * 2) >= mask
end
function service:Get(unit)
    if not UnitGUID then return nil end
    local guid = UnitGUID(unit)
    if type(guid) ~= "string" then return nil end
    if issecretvalue and issecretvalue(guid) then return nil end
    local npcID = guid:match("^Creature%-[^%-]*%-[^%-]*%-[^%-]*%-[^%-]*%-(%d+)%-")
        or guid:match("^Vehicle%-[^%-]*%-[^%-]*%-[^%-]*%-[^%-]*%-(%d+)%-")
    if not npcID then return nil end
    local flags = flagsByID[tonumber(npcID)]
    if not flags then return nil end
    return {
        vendor = has(flags, 4), flight = has(flags, 8),
        trainer = has(flags, 16), inn = has(flags, 128),
        bank = has(flags, 256), auction = has(flags, 4096),
        stable = has(flags, 8192), repair = has(flags, 16384),
    }
end